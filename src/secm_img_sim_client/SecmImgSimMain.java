    /**
     * Reads from the rightmost column of {@link #FILE_PATH_DATA} and returns the result as an array of doubles
     * @return 
     * @throws FileNotFoundException 
     */
    static double[] readData() throws FileNotFoundException{
        File f = new File(FILE_PATH_DATA);
        Scanner s = new Scanner(f);
        int count = 0;
        while(s.hasNextLine()){
            String ln = s.nextLine();
            if(!ln.startsWith("%")){
                count ++;
            }
        }
        s.close();
        double[] data = new double[count];
        s = new Scanner(f);
        count = 0;
        while(s.hasNextLine()){
            String ln = s.nextLine();
            if(!ln.startsWith("%")){
                String[] linedata = ln.trim().split("\\s+");// split whilespace separated columns
                data[count] = Double.parseDouble(linedata[linedata.length -1]);//read from the rightmost column
                count ++;
            }
        }
        s.close();
        return data;
    }
    
