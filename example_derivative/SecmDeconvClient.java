    /**
     * 
     * @param list
     * @param value 
     */
    private static void addInOrder(LinkedList<Double> list, double value){
        if(!list.isEmpty()){
            ListIterator<Double> list_li = list.listIterator();
            boolean placed = false;
            while(list_li.hasNext() && !placed){
                double current = list_li.next();
                if(tolerantEquals(current, value, false)){
                    placed = true;
                }
                else if (current > value){
                    list_li.previous();
                    list_li.add(value);
                    placed = true;
                }
            }
            if(!placed){
                list_li.add(value);
            }
        }
        else{
            list.add(value);
        }
    }
    
    /**
     * Converts a scaled current signal to the approximate logk value that may have generated it.
     * This serves as an inverse for {@link #logKappaToCurrent(double)}.
     * Newton's method is used to approximate this logk value.
     * @param current The scaled current as a value between 0 and 1.
     * @return the logk that will result in current when used as an argument for {@link #logKappaToCurrent(double)}.
     */
    static double currentToLogKappa(double current){
        int len_m1 = ki_currents.length - 1;
        if(ki_currents[0] < ki_currents[len_m1]){//ascending order
            if(current > ki_currents[0] && current < ki_currents[len_m1]){
                int lower = findLower(ki_currents, current);
                double kappa_lower = ki_logks[lower];
                double kappa_upper = ki_logks[lower + 1];
                double current_lower = ki_currents[lower];
                double current_upper = ki_currents[lower + 1];

                double current_distance = current_upper - current_lower;
                double fact_lower = (current_upper - current)/current_distance;
                double fact_upper = 1.0-fact_lower;
                return kappa_lower*fact_lower + kappa_upper*fact_upper;
            }
            else if(current <= ki_currents[0]){
                return ki_logks[0];
            }
            else{
                return ki_logks[len_m1];
            }
        }
        else{//descending order
            if(current < ki_currents[0] && current > ki_currents[len_m1]){
                int upper = findGreater(ki_currents, current);
                double kappa_upper = ki_logks[upper];
                double kappa_lower = ki_logks[upper + 1];
                double current_upper = ki_currents[upper];
                double current_lower = ki_currents[upper + 1];

                double current_distance = current_upper - current_lower;
                double fact_lower = (current_upper - current)/current_distance;
                double fact_upper = 1.0-fact_lower;
                return kappa_lower*fact_lower + kappa_upper*fact_upper;
            }
            else if(current <= ki_currents[len_m1]){
                return ki_logks[len_m1];
            }
            else{
                return ki_logks[0];
            }
        }
    }
    
    /**
     * Decodes the bytes representing a k-image from the server and puts the data into img_x_coordinates, img_y_coordinates, img_kappas
     * @param encoded_image
     * @throws IOException 
     */
    private static void decodeIncomingKImage(byte[] encoded_image) throws IOException{
        String crlf = "\r\n";
        byte[] crlf_data = crlf.getBytes(CHARSET);
        byte[] crlf_detection_buffer = new byte[crlf_data.length];
        int endx = 0;
        //Scan until the CRLF
        for(int i = 0; i < encoded_image.length; i++){
            for(int cdb = 0; cdb < crlf_data.length - 1; cdb ++){
                crlf_detection_buffer[cdb] = crlf_detection_buffer[cdb + 1];
            }
            crlf_detection_buffer[crlf_data.length - 1] = encoded_image[i];
            boolean line_end = true;
            for(int cdb = 0; cdb < crlf_data.length; cdb++){
                if(crlf_detection_buffer[cdb] != crlf_data[cdb]){
                    line_end = false;
                    break;
                }
            }
            if(line_end){
                endx = i;
                break;
            }
        }
        if(endx == 0){
            throw new IOException("No CRLF encountered when decoding image.");
        }
        
        crlf_detection_buffer = new byte[crlf_data.length];
        int endy = endx;
        //scan until second CRLF
        for(int i = endx; i < encoded_image.length; i++){
            for(int cdb = 0; cdb < crlf_data.length - 1; cdb ++){
                crlf_detection_buffer[cdb] = crlf_detection_buffer[cdb + 1];
            }
            crlf_detection_buffer[crlf_data.length - 1] = encoded_image[i];
            boolean line_end = true;
            for(int cdb = 0; cdb < crlf_data.length; cdb++){
                if(crlf_detection_buffer[cdb] != crlf_data[cdb]){
                    line_end = false;
                    break;
                }
            }
            if(line_end){
                endy = i;
                break;
            }
        }
        if(endy == endx){
            throw new IOException("No CRLF encountered beyond the first line when decoding image.");
        }
        //parse-out the x and y dimensions of the image
        endx ++;
        endy ++;
        byte[] length_line_x_bytes = new byte[endx];
        byte[] length_line_y_bytes = new byte[endy - endx];
        System.arraycopy(encoded_image, 0, length_line_x_bytes, 0, endx);
        System.arraycopy(encoded_image, endx, length_line_y_bytes, 0, endy - endx);
        String length_line_x = new String(length_line_x_bytes, CHARSET);
        String length_line_y = new String(length_line_y_bytes, CHARSET);
        if(!length_line_x.startsWith("xlen: ")){
            throw new IOException("Image x-size line did not start as expected: " + length_line_x);
        }
        if(!length_line_y.startsWith("ylen: ")){
            throw new IOException("Image y-size line did not start as expected: " + length_line_y);
        }
        String length_part_x = length_line_x.substring(6, length_line_x.length() - crlf_data.length);
        String length_part_y = length_line_y.substring(6, length_line_y.length() - crlf_data.length);
        int xlen = Integer.parseInt(length_part_x);
        int ylen = Integer.parseInt(length_part_y);
        //check expected size against actual size
        //int expected_encoded_length = xlen*8 + ylen*8 + xlen*ylen*8 + endx + endy + CRLF.length*3;
        int expected_encoded_length = xlen*8 + ylen*8 + xlen*ylen*8 + endy + crlf_data.length*3;
        int actual_encoded_length = encoded_image.length;
        if(expected_encoded_length != actual_encoded_length){
            throw new IOException(String.format("Expected content length of %d bytes. Received: %d", expected_encoded_length, actual_encoded_length));
        }
        
        byte[] byte_data_x = new byte[xlen*8];
        byte[] byte_data_y = new byte[ylen*8];
        byte[] byte_data_image = new byte[xlen*ylen*8];
        System.arraycopy(encoded_image, endy, byte_data_x, 0, xlen*8);
        System.arraycopy(encoded_image, endy + xlen*8 + crlf_data.length, byte_data_y, 0, ylen*8);
        System.arraycopy(encoded_image, endy + xlen*8 + ylen*8 + crlf_data.length*2, byte_data_image, 0, xlen*ylen*8);
        
        //convert byte arrays to doubles.
        ByteBuffer x_bb = ByteBuffer.wrap(byte_data_x).order(ENDIANNESS);
        ByteBuffer y_bb = ByteBuffer.wrap(byte_data_y).order(ENDIANNESS);
        ByteBuffer img_bb = ByteBuffer.wrap(byte_data_image).order(ENDIANNESS);
        
        img_x_coordinates = new double[xlen];
        img_y_coordinates = new double[ylen];
        img_kappas = new double[xlen][ylen];
        
        for(int x = 0; x < xlen; x++){
            int xcontrib = x*ylen;
            img_x_coordinates[x] = x_bb.getDouble(x*8);
            for(int y = 0; y < ylen; y++){
                int indx = (xcontrib + y)*8;
                img_kappas[x][y] = img_bb.getDouble(indx);
            }
        }
        
        for(int y= 0; y < ylen; y++){
            img_y_coordinates[y] = y_bb.getDouble(y*8);
        }
    }
    
    /**
     * <p>Encodes a logk - current curve into a byte array for sending over a network connection.</p>
     * <p>Data is encoded according to the following format:</p>
     * <code><p>"len: %d\r\n"</p>
     * <p>[Binary data containing logks] + "\r\n"</p>
     * <p>[Binary data containing currents] + "\r\n"</p></code>
     * <p>Doubles are converted to bytes using {@link #ENDIANNESS} endianness</p>
     * <p></p>
     * @param logks a double array comprising the logk data
     * @param currents a double array comprising the current data
     * @return the logk - current encoded as a byte array
     */
    private static byte[] encodeCurve(double[] logks, double[] currents){
        /*
        "len: %d\r\n", len
        [Binary data containing logks] + "\r\n"
        [Binary data containing currents] + "\r\n"
        */
        int len = logks.length;
        String first_line = String.format("len: %d\r\n", len);
        String crlf = "\r\n";
        
        byte[] first_line_data = first_line.getBytes(CHARSET);
        byte[] crlf_data = crlf.getBytes(CHARSET);
        byte[] logk_data = new byte[len*8];
        byte[] current_data = new byte[len*8];
        
        ByteBuffer logk_bb = ByteBuffer.wrap(logk_data).order(ENDIANNESS);
        ByteBuffer current_bb = ByteBuffer.wrap(current_data).order(ENDIANNESS);
        
        for(int i = 0; i < logks.length; i++){
            logk_bb.putDouble(i*8, logks[i]);
            current_bb.putDouble(i*8, currents[i]);
        }
        
        //Append the data together
        int block_length = first_line_data.length + logk_data.length + current_data.length + 2*crlf_data.length;
        byte[] block_data = new byte[block_length];
        int running_length = 0;
        System.arraycopy(first_line_data, 0, block_data, 0, first_line_data.length);
        running_length += first_line_data.length;
        System.arraycopy(logk_data, 0, block_data, running_length, logk_data.length);
        running_length += logk_data.length;
        System.arraycopy(crlf_data, 0, block_data, running_length, crlf_data.length);
        running_length += crlf_data.length;
        System.arraycopy(current_data, 0, block_data, running_length, current_data.length);
        running_length += current_data.length;
        System.arraycopy(crlf_data, 0, block_data, running_length, crlf_data.length);
        return block_data;
    }
    
    /**
     * <p>Encodes image data into a byte array for sending over a network connection.</p>
     * <p>Data is encoded according to the following format:</p>
     * <code><p>"xlen: %d\r\n"</p>
     * <p>"ylen: %d\r\n"</p>
     * <p>[Binary data containing xs] + "\r\n"</p>
     * <p>[Binary data containing ys] + "\r\n"</p>
     * <p>[Binary data containing signals] + "\r\n"</p></code>
     * <p>Doubles are converted to bytes using {@link #ENDIANNESS} endianness</p>
     * <p>The image signal data is mapped to one dimension as a series of scans in the y-direction i.e.:</p>
     * <code><p>for(x = 0 -> xlen)</p>
     * <p>  for(y = 0 -> ylen)</p>
     * <p>      Append signal[x][y] to byte array</p>
     * <p>  end for</p>
     * <p>end for</p></code>
     * <p></p>
     * @param xs a double array comprising the x coordinates of the pixels in the image
     * @param ys a double array comprising the y coordinates of the pixels in the image
     * @param signals a double array containing the signal data of the image. 
     * Indexed as signals[x][y]
     * @return the image data as a byte array
     */
    private static byte[] encodeImage(double[] xs, double[] ys, double[][] signals){
        /*
        "xlen: %d\r\n", xlen
        "ylen: %d\r\n", ylen
        [Binary data containing xs] + "\r\n"
        [Binary data containing ys] + "\r\n"
        [Binary data containing signals] + "\r\n"
        */
        int xlen = xs.length;
        int ylen = ys.length;
        String size_lines = String.format("xlen: %d\r\nylen: %d\r\n", xlen, ylen);
        String crlf = "\r\n";
        
        byte[] size_line_data = size_lines.getBytes(CHARSET);
        byte[] crlf_data = crlf.getBytes(CHARSET);
        byte[] x_data = new byte[xlen*8];
        byte[] y_data = new byte[ylen*8];
        byte[] img_data = new byte[xlen*ylen*8];
        
        ByteBuffer x_bb = ByteBuffer.wrap(x_data).order(ENDIANNESS);
        ByteBuffer y_bb = ByteBuffer.wrap(y_data).order(ENDIANNESS);
        ByteBuffer img_bb = ByteBuffer.wrap(img_data).order(ENDIANNESS);
        
        for(int i = 0; i < xs.length; i++){
            x_bb.putDouble(i*8, xs[i]);
        }
        for(int i = 0; i < ys.length; i++){
            y_bb.putDouble(i*8, ys[i]);
        }
        for(int x = 0; x < xlen; x++){
            int xcontrib = x*ylen;
            for(int y = 0; y < ylen; y++){
                int indx = xcontrib + y;
                img_bb.putDouble(indx*8, signals[x][y]);
            }
        }
        
        //Append the data together
        int block_length = size_line_data.length + x_data.length + y_data.length + img_data.length + 3*crlf_data.length;
        byte[] block_data = new byte[block_length];
        int running_length = 0;
        System.arraycopy(size_line_data, 0, block_data, 0, size_line_data.length);
        running_length += size_line_data.length;
        System.arraycopy(x_data, 0, block_data, running_length, x_data.length);
        running_length += x_data.length;
        System.arraycopy(crlf_data, 0, block_data, running_length, crlf_data.length);
        running_length += crlf_data.length;
        System.arraycopy(y_data, 0, block_data, running_length, y_data.length);
        running_length += y_data.length;
        System.arraycopy(crlf_data, 0, block_data, running_length, crlf_data.length);
        running_length += crlf_data.length;
        System.arraycopy(img_data, 0, block_data, running_length, img_data.length);
        running_length += img_data.length;
        System.arraycopy(crlf_data, 0, block_data, running_length, crlf_data.length);
        return block_data;
    }
    
