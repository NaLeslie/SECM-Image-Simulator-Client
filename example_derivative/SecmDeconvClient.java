    /**
     * 
     * @param array
     * @param key
     * @param min
     * @param max
     * @return 
     */
    private static int findEqual(double[] array, double key, int min, int max){
        boolean use_relative = false;
        if(tolerantEquals(key, array[min], use_relative)){
            return min;
        }
        else if(tolerantEquals(key, array[max], use_relative)){
            return max;
        }
        else if(array[min] > key || array[max] < key){
            return -1;
        }
        else{
            int mid = (max - min) / 2 + min;
            if(tolerantEquals(key, array[mid], use_relative)){
                return mid;
            }
            else if(array[mid] < key){
                return findEqual(array, key, mid, max);
            }
            else{
                return findEqual(array, key, min, mid);
            }
        }
    }
    
    /**
     * Binary searches through an descending order array to find the largest index such that array[index] &gt; value.
     * Will return -1 if all elements of array are &lt; value
     * @param array array of values sorted in descending order.
     * @param value the value that is being searched-for.
     * @return 
     */
    private static int findGreater(double[] array, double value){
        if(array[0] > value){
            return 0;
        }
        if(array[array.length - 1] < value){
            return array.length - 1;
        }
        return findGreater(array, value, 0, array.length - 1);
    }
    
    /**
     * USE {@link #findGreater(double[], double) } instead.
     * @param array
     * @param value
     * @param start
     * @param stop
     * @return 
     */
    private static int findGreater(double[] array, double value, int start, int stop){
        
        if(stop - start == 1){
            return stop;
        }
        else if(stop - start == 2){
            if(array[start + 1] > value){
                return start + 1;
            }
            else{
                return stop;
            }
        }
        else{
            int mid = (stop - start)/2 + start;
            if(array[mid] < value){
                return findGreater(array, value, mid, stop); 
            }
            else{
                return findGreater(array, value, start, mid);
            }
        }
    }
    
